#ifndef DEFAULT_ERROR_PAGE_HPP
#define DEFAULT_ERROR_PAGE_HPP

#include <string>

// C++98-compatible helper to build a tiny HTML error page body.
inline std::string httpStatusReason(int status) {
    switch (status) {
        case 200: return "OK";
        case 201: return "Created";
        case 204: return "No Content";
        case 301: return "Moved Permanently";
        case 302: return "Found";
        case 400: return "Bad Request";
        case 403: return "Forbidden";
        case 404: return "Not Found";
        case 405: return "Method Not Allowed";
        case 413: return "Payload Too Large";
        case 500: return "Internal Server Error";
        case 502: return "Bad Gateway";
        case 504: return "Gateway Timeout";
        default:  return "Error";
    }
}

inline std::string generateDefaultErrorHtml(int status) {
    const std::string reason = httpStatusReason(status);
    std::string html;
    html.reserve(512);
    html  = "<!doctype html><html><head><meta charset=\"utf-8\">";
    html += "<title>";
    html += httpStatusReason(status);
    html += "</title>";
    html += "<style>body{font-family:Segoe UI,Roboto,Arial,sans-serif;padding:40px;background:#f8f9fb;color:#222}";
    html += "h1{margin:0 0 12px;font-size:28px;color:#c62828}p{opacity:.8;margin:0}";
    html += "code{background:#eee;padding:2px 6px;border-radius:4px}</style></head><body>";
    html += "<h1>";
    html += reason;
    html += " (";
    // Convert status int to string (C++98)
    {
        char buf[16];
        #ifdef _MSC_VER
            _snprintf(buf, 16, "%d", status);
        #else
            snprintf(buf, 16, "%d", status);
        #endif
        html += buf;
    }
    html += ")</h1>";
    html += "<p>Generated by <code>webserv</code>.</p>";
    html += "</body></html>";
    return html;
}

#endif // DEFAULT_ERROR_PAGE_HPP
